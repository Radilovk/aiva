#!/usr/bin/env node
/**
 * Bundles workers/src/school/browser.ts (engine + questionnaire) for the operator console:
 *
 *   node scripts/build-school-engine.mjs           -> frontend/school/lib/sf-engine.js
 *   node scripts/build-school-engine.mjs --check   -> exit 1 if the committed bundle is stale
 *
 * The bundle is committed because GitHub Pages and the Worker's static assets serve frontend/ as is.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'frontend/school/lib/sf-engine.js');
const code = execFileSync(join(root, 'workers/node_modules/.bin/esbuild'), [
  join(root, 'workers/src/school/browser.ts'), '--bundle', '--format=iife', '--global-name=SFEngine',
  '--target=es2020', '--minify', '--legal-comments=none', '--log-level=warning',
], { encoding: 'utf8' });
const text = `/* Generated by scripts/build-school-engine.mjs from workers/src/school – do not edit. */\n${code}`;

if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== text) { console.error('frontend/school/lib/sf-engine.js is stale: run node scripts/build-school-engine.mjs'); process.exit(1); }
  console.log('sf-engine.js is up to date');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${out} (${Math.round(text.length / 1024)} KB)`);
}
