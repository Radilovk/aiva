function buildLang(lang) {
  const out = {};
  const locale = LOCALE_STRINGS[lang] || {};
  for (const [key, pair] of Object.entries(KEYS)) {
    if (lang === 'en') out[key] = pair[0];
    else if (lang === 'bg') out[key] = pair[1];
    else if (locale[key]) out[key] = locale[key];
    else if (MANUAL[lang]?.[key]) out[key] = MANUAL[lang][key];
    else out[key] = pair[0];
  }
  return out;
}

const EXT = {};
for (const lang of LANGS) EXT[lang] = buildLang(lang);

